package util

import "testing"

// TestStripSiteOperationMarkers_EmptyShellTail §59.375: 尾部空壳括号族
// （跨站传播退化——keepfrds FRDS 官种标记转载丢失，121 行实证）。
// 仅防御空壳：纯空白内容（含 NBSP）的四种括号；有内容不碰；尾部锚定。
func TestStripSiteOperationMarkers_EmptyShellTail(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
	}{
		// 本案实证形态（阿玲 rss_detail 行 hex 实录：空格+3NBSP+空格+[]）
		{"地道战空壳实录", "【地道战】10bit HEVC版本 国语 简繁英字幕 \u00a0\u00a0\u00a0 []", "【地道战】10bit HEVC版本 国语 简繁英字幕"},
		{"普通空格前缀", "简繁英字幕 []", "简繁英字幕"},
		{"多空壳连排", "简繁英字幕 [] []", "简繁英字幕"},
		// 三种扩展形态（防御性——零实证但语义同族）
		{"中文方括号空壳", "简繁英字幕 【】", "简繁英字幕"},
		{"半角圆括号空壳", "简繁英字幕 ()", "简繁英字幕"},
		{"全角圆括号空壳", "简繁英字幕 （）", "简繁英字幕"},
		{"混排空壳", "简繁英字幕 [] 【】", "简繁英字幕"},
		// 有内容一律不碰（词表族管——空壳族不得越权）
		{"有内容方括号保留", "标题 [国粤语]", "标题 [国粤语]"},
		{"词表外内容保留", "标题 [自定义标注]", "标题 [自定义标注]"},
		{"NBSP 内容非空白保留", "标题 [\u00a0中\u00a0]", "标题 [\u00a0中\u00a0]"},
		// 尾部锚定——中间空壳不剥（防误伤内容性标题结构）
		{"中间空壳不剥", "标题 [] 副标题文字", "标题 [] 副标题文字"},
		// 与词表族协同（混排：有内容标记+空壳连排全清）
		{"词表标记后跟空壳", "标题 [50%] []", "标题"},
		{"免费标记后跟空壳", "标题 [免费]()", "标题"},
		// 整串空壳 → 空（族一同款边界）
		{"纯空壳", "[]", ""},
	}
	for _, c := range cases {
		if got := StripSiteOperationMarkers(c.in); got != c.want {
			t.Errorf("%s: in=%q got=%q want=%q", c.name, c.in, got, c.want)
		}
	}
}
